-- Run with an administrative setup role. Replace the three ALL_CAPS placeholders first.
CREATE DATABASE IF NOT EXISTS RETAIL_QE;
CREATE WAREHOUSE IF NOT EXISTS RETAIL_QE_WH
  WAREHOUSE_SIZE='XSMALL' AUTO_SUSPEND=60 AUTO_RESUME=TRUE INITIALLY_SUSPENDED=TRUE;
CREATE ROLE IF NOT EXISTS RETAIL_QE;
GRANT USAGE ON WAREHOUSE RETAIL_QE_WH TO ROLE RETAIL_QE;
GRANT USAGE ON DATABASE RETAIL_QE TO ROLE RETAIL_QE;
CREATE SCHEMA IF NOT EXISTS RETAIL_QE.RAW;
CREATE SCHEMA IF NOT EXISTS RETAIL_QE.ANALYTICS;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA RETAIL_QE.RAW TO ROLE RETAIL_QE;
GRANT USAGE, CREATE TABLE, CREATE VIEW ON SCHEMA RETAIL_QE.ANALYTICS TO ROLE RETAIL_QE;
CREATE STORAGE INTEGRATION IF NOT EXISTS RETAIL_S3_INTEGRATION
 TYPE=EXTERNAL_STAGE STORAGE_PROVIDER=S3 ENABLED=TRUE
 STORAGE_AWS_ROLE_ARN='arn:aws:iam::YOUR_ACCOUNT_ID:role/retail-qe-snowflake-read'
 STORAGE_ALLOWED_LOCATIONS=('s3://YOUR_BUCKET/retail-qe/');
DESC INTEGRATION RETAIL_S3_INTEGRATION;
-- Complete the AWS trust-policy handshake described in docs/CLOUD_RUNBOOK.md before COPY.
GRANT USAGE ON INTEGRATION RETAIL_S3_INTEGRATION TO ROLE RETAIL_QE;
CREATE STAGE IF NOT EXISTS RETAIL_QE.RAW.RETAIL_STAGE
 URL='s3://YOUR_BUCKET/retail-qe/run-001/'
 STORAGE_INTEGRATION=RETAIL_S3_INTEGRATION FILE_FORMAT=(TYPE=PARQUET);
GRANT USAGE ON STAGE RETAIL_QE.RAW.RETAIL_STAGE TO ROLE RETAIL_QE;
